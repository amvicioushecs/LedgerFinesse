import { en } from "@/content/dictionaries.en";
import { listPosts } from "@/lib/blog";
import { siteUrl } from "@/lib/seo";

/** llms.txt built from the live copy, so pricing and claims can't drift from the site. */
export function GET() {
  const origin = siteUrl();
  const posts = listPosts("en").filter((p) => !p.draft);
  const lines = [
    "# LedgerFinesse",
    "",
    `> ${en.meta.description} ${en.disclaimer}`,
    "",
    "LedgerFinesse is an educational tool, not a law firm, and does not give legal advice.",
    "",
    "## Pages",
    `- [Home (English)](${origin}/en): How it works, what the audit checks, pricing (15% of the amount owed, paid upfront, with a $0.50 minimum; free if less than $0.50 is owed) and FAQ.`,
    `- [Inicio (Español)](${origin}/es): La misma información en español.`,
    `- [Sample audit](${origin}/en/sample): A SAMPLE report for a fictional San Diego tenant, generated by the same rules engine.`,
    `- [Guides](${origin}/en/blog): Renter guides with official sources.`,
    ...posts.map((p) => `- [${p.title}](${origin}/en/blog/${p.slug}): ${p.description}`),
    "",
    "## FAQ",
    ...en.faq.items.flatMap((item) => [`### ${item.q}`, item.a, ""]),
  ];
  return new Response(lines.join("\n"), { headers: { "content-type": "text/plain; charset=utf-8" } });
}
