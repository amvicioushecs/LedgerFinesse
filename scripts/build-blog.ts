/** Compiles content/blog into src/content/blog.generated.ts (run by `npm run blog:build`, before builds). */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { compileAll } from "../src/lib/blog/compile";

const posts = compileAll();
const out = path.join(process.cwd(), "src/content/blog.generated.ts");
writeFileSync(
  out,
  `// GENERATED by scripts/build-blog.ts from content/blog. Do not edit.\nimport type { BlogPost } from "@/lib/blog/types";\n\nexport const POSTS: BlogPost[] = ${JSON.stringify(posts, null, 2)};\n`,
);
console.log(`blog: wrote ${posts.length} posts to ${path.relative(process.cwd(), out)}`);
